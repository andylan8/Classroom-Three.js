const scale = 20;

const fountain_center_shape = create_shape_from_verticies(fountain_center_verts, scale, scale);
const fountain_base_shape = create_shape_from_verticies(fountain_base_verts, scale, scale);

const fountain_center_geom = new THREE.LatheGeometry(fountain_center_shape.getPoints(), 32);
const fountain_base_geom = new THREE.LatheGeometry(fountain_base_shape.getPoints(), 32);

const fountain_base_mat = create_material_from_texture("./textures/Concrete");//new THREE.MeshStandardMaterial({ color: 0x808080, side: THREE.DoubleSide });
fountain_base_mat.side = THREE.DoubleSide;

const fountain_center_mat = fountain_base_mat; //new THREE.MeshStandardMaterial({ color: 0x808080, side: THREE.BackSide });

const fountain_center = new THREE.Mesh(fountain_center_geom, fountain_center_mat);
const fountain_base = new THREE.Mesh(fountain_base_geom, fountain_base_mat);

export const fountain = new THREE.Group();

fountain_center.castShadow = true;
fountain_center.receiveShadow = false;

fountain_base.castShadow = true;
fountain_base.receiveShadow = false;

const waterGeometry = new THREE.CircleGeometry( 15, 32 );

export const water = new Water(
    waterGeometry,
    {
        textureWidth: 512,
        textureHeight: 512,
        waterNormals: new THREE.TextureLoader().load('./textures/waternormals.jpg', function ( texture ) {
            texture.wrapS = texture.wrapT = THREE.RepeatWrapping;
        } ),
        sunDirection: new THREE.Vector3(),
        sunColor: 0xffffff,
        waterColor: 0x001e0f,
        distortionScale: 3.7,
        fog: false
    }
);

water.translateY(-7);
water.rotation.x = - Math.PI / 2;

fountain.add(fountain_center);
fountain.add(fountain_base);
fountain.add(water);

fountain.position.set(-120, 10.5, 140);